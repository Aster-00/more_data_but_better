"""SR08-SR13 repair tests against the same SR07 cells (D-025, D-026).

All are test-contaminated like SR07, so they are judged on dev; test columns are leakage analysis.
Per variant, only the BERT x generator cells it ran, with the same seeds in SR07 and SR01:
  1. scores   dev and test macro F1 and F1-PN, test F1 per class, mean over cells; Δ against SR07 per cell with
              "better in" counts and a two-sided sign test over the cells
  2. subsets  test error rate on gold POS tweets with the religious cue, all gold POS tweets, hard
              cases and other tweets (as src.sentiment.sg04_analysis)
  3. epochs   which epoch dev picked: in SR10-SR13 the real-only stage only took effect in runs that picked epoch 3
  4. no NEU   SR12 / SR13 against SR11, SR01 and each other, per class on dev and test, and gold NEU predicted NEG

Outputs: docs/sentiment/tables/sg04_repair.md, results/sentiment/analysis/sg04_repair.json.

Usage:
  python -m src.sentiment.sg04_repair
"""
from __future__ import annotations

import csv
import json
import re
import statistics
import sys
from collections import Counter
from pathlib import Path

from src.sentiment.hard_cases import CUES
from src.sentiment.sg04_analysis import HARD, RUNS_DIR, TEST, sign_p, table

BERTS = ["marbertv2", "arabertv02_twitter", "camelbert_mix"]
SEEDS = [42, 43, 44]
VARIANTS = {"SR08": ("no prayer pairs", ["fanar", "qwen3", "aya"]), "SR09": ("no same-word pairs", ["qwen3"]),
            "SR10": ("two-stage", ["fanar", "qwen3", "aya"]),
            "SR11": ("no prayer pairs + two-stage", ["fanar", "qwen3", "aya"]),
            "SR12": ("SR11, POS/NEG pairs only", ["fanar", "qwen3", "aya"]),
            "SR13": ("SR12 + NEG sides of jab and remark", ["fanar", "qwen3", "aya"])}
# Paired comparisons of the no-NEU runs (D-026): SR13 - SR12 is the effect of the 1,000 NEG sides.
NO_NEU_PAIRS = [("SR12", "SR11"), ("SR13", "SR11"), ("SR13", "SR12"), ("SR12", "SR01"), ("SR13", "SR01")]


def load(run: str) -> tuple[dict, list[str]]:
    """Train log and test predictions of one run folder."""
    d = RUNS_DIR / run
    log = json.loads((d / "train_log.json").read_text(encoding="utf-8"))
    with open(d / "test_predictions.jsonl", encoding="utf-8") as f:
        return log, [json.loads(l)["pred"] for l in f]


def scores(log: dict) -> dict[str, float]:
    """The compared scores of one run."""
    return {"dev": log["dev"]["macro"]["f1"], "test": log["test"]["macro"]["f1"],
            "dev_pn": log["dev"]["f1_pn"], "test_pn": log["test"]["f1_pn"],
            **{f"{s}_{c}": log[s]["per_class"][c]["f1"] for s in ("dev", "test") for c in ("NEG", "NEU", "POS")}}


def main() -> None:
    """Compare every variant with SR07 and SR01 on its own cells; write the table."""
    sys.stdout.reconfigure(encoding="utf-8")
    with open(TEST, encoding="utf-8") as f:
        test = [json.loads(l) for l in f]
    gold = [r["sentiment"] for r in test]
    with open(HARD, encoding="utf-8-sig") as f:
        hard_ids = {r["text_id"] for r in csv.DictReader(f)}
    subsets = {"Gold POS, religious cue": [i for i, r in enumerate(test) if gold[i] == "POS" and re.search(CUES["religious"], r["text"])],
               "All gold POS": [i for i in range(len(test)) if gold[i] == "POS"],
               "Hard cases": [i for i, r in enumerate(test) if r["text_id"] in hard_ids],
               "Other test tweets": [i for i, r in enumerate(test) if r["text_id"] not in hard_ids]}

    def cell(pattern: str) -> tuple[dict[str, float], dict[str, float], list[int]]:
        """Mean scores and subset errors of a cell over its seeds, and the epochs dev picked."""
        runs = [load(f"{pattern}_seed{s}") for s in SEEDS]
        sc = {k: statistics.fmean(scores(l)[k] for l, _ in runs) for k in scores(runs[0][0])}
        er = {n: statistics.fmean(sum(p[i] != gold[i] for i in idx) / len(idx) for _, p in runs) for n, idx in subsets.items()}
        # Share of gold NEU test tweets predicted NEG (the error the jab and remark NEG sides may cause, SA-E03).
        neu = [i for i, g in enumerate(gold) if g == "NEU"]
        er["NEU to NEG"] = statistics.fmean(sum(p[i] == "NEG" for i in neu) / len(neu) for _, p in runs)
        return sc, er, [l["best_epoch"] for l, _ in runs]

    md = ["# SR08–SR13: repair tests on SG04 (test-contaminated, D-025, D-026)", "",
          "Generated by `python -m src.sentiment.sg04_repair`. Do not edit by hand. BERTs: MARBERTv2, AraBERTv02-Tw, "
          "CAMeLBERT-mix; seeds 42/43/44. Each row compares only the cells that variant ran. Judge on dev: test columns are "
          "leakage analysis. Sign test over cells; with 3 or 9 cells it can only show large effects. F1-PN = mean F1 of POS "
          "and NEG, the official ArSarcasm-v2 metric.", ""]
    keys = ["dev", "dev_pn", "test", "test_pn", "test_NEG", "test_NEU", "test_POS"]
    score_rows, delta_rows, subset_rows, out = [], [], [], {}
    epochs: dict[str, Counter] = {}
    for sr, (name, gens) in VARIANTS.items():
        cells = [(b, g) for b in BERTS for g in gens]
        var = [cell(f"{sr.lower()}_{b}_{g}") for b, g in cells]
        base = [cell(f"sr07_{b}_{g}") for b, g in cells]
        real = [cell(f"sr01_{b}") for b, _ in cells]
        mean = lambda data, k, j=0: statistics.fmean(c[j][k] for c in data)
        for label, data in ((f"SR01 (real only, {len(cells)} cells)", real), (f"SR07 ({len(cells)} cells)", base), (f"{sr} {name}", var)):
            score_rows.append([label] + [f"{mean(data, k):.2f}" for k in keys])
        out[sr] = {"cells": len(cells)}
        row = [f"{sr} − SR07 ({name})"]
        for k in ("dev", "dev_pn", "test", "test_pn"):
            ds = [v[0][k] - s[0][k] for v, s in zip(var, base)]
            out[sr][k] = {"delta": statistics.fmean(ds), "better": sum(d > 0 for d in ds), "p": sign_p(ds)}
            row.append(f"{statistics.fmean(ds):+.2f} (better in {sum(d > 0 for d in ds)}/{len(ds)}, p = {sign_p(ds):.3f})")
        delta_rows.append(row)
        for n in subsets:
            subset_rows.append([sr, n, f"{len(subsets[n]):,}"] + [f"{100 * mean(d, n, 1):.1f}%" for d in (real, base, var)])
        epochs[sr] = Counter(e for v in var for e in v[2])
    md += ["## Scores", ""] + table(["Run", "Dev macro F1", "Dev F1-PN", "Test macro F1", "Test F1-PN", "Test F1 NEG", "Test F1 NEU", "Test F1 POS"], score_rows) + [""]
    md += ["## Change against SR07", ""] + table(["Comparison", "Dev", "Dev F1-PN", "Test", "Test F1-PN"], delta_rows) + [""]
    md += ["## Test error rate on subsets", ""] + table(["Variant", "Subset", "Tweets", "SR01", "SR07", "Variant error"], subset_rows) + [""]
    rows = [[sr] + [str(epochs[sr].get(e, 0)) for e in (1, 2, 3)] for sr in VARIANTS]
    md += ["## Epoch picked by dev", "", "In SR10–SR13 the real-only stage took effect only in runs that picked epoch 3.", ""]
    md += table(["Run", "Epoch 1", "Epoch 2", "Epoch 3"], rows) + [""]
    out["epochs"] = {k: dict(v) for k, v in epochs.items()}

    # SR12 / SR13: paired by BERT x generator cell; Δ per class, with the gold NEU predicted NEG share on test.
    cells = [(b, g) for b in BERTS for g in ("fanar", "qwen3", "aya")]
    by_run = {sr: [cell(f"sr01_{b}" if sr == "SR01" else f"{sr.lower()}_{b}_{g}") for b, g in cells]
              for sr in ("SR01", "SR11", "SR12", "SR13")}
    cols = ["dev", "dev_NEG", "dev_NEU", "dev_POS", "test", "test_NEG", "test_NEU", "test_POS"]
    level_rows = [[sr] + [f"{statistics.fmean(c[0][k] for c in data):.2f}" for k in cols]
                  + [f"{100 * statistics.fmean(c[1]['NEU to NEG'] for c in data):.1f}%"] for sr, data in by_run.items()]
    pair_rows = []
    for a, b in NO_NEU_PAIRS:
        row = [f"{a} − {b}"]
        for k in cols:
            ds = [x[0][k] - y[0][k] for x, y in zip(by_run[a], by_run[b])]
            row.append(f"{statistics.fmean(ds):+.2f} ({sum(d > 0 for d in ds)}/{len(ds)})")
            out.setdefault("no_neu", {}).setdefault(f"{a}-{b}", {})[k] = {"delta": statistics.fmean(ds), "better": sum(d > 0 for d in ds), "p": sign_p(ds)}
        pair_rows.append(row)
    names = ["Dev macro", "Dev NEG", "Dev NEU", "Dev POS", "Test macro", "Test NEG", "Test NEU", "Test POS"]
    md += ["## SR12 / SR13: without the NEU generations (D-026)", "",
           "Same 9 cells. SR13 − SR12 is the effect of the 1,000 NEG sides of public jab and personal remark. "
           "Size also changes: SR11 3,600 texts, SR12 1,600, SR13 2,600.", ""]
    md += table(["Run"] + names + ["Test gold NEU predicted NEG"], level_rows) + [""]
    md += ["Δ F1 per pair (cells better, of 9):", ""] + table(["Comparison"] + names, pair_rows) + [""]

    Path("docs/sentiment/tables/sg04_repair.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    Path("results/sentiment/analysis/sg04_repair.json").write_text(json.dumps(out, indent=2), encoding="utf-8", newline="\n")
    print("\n".join(md))


if __name__ == "__main__":
    sys.exit(main())
