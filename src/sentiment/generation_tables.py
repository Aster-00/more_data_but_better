"""Full result table per generation run: every classifier x generator, macro F1, F1-PN and F1 per class.

From docs/sentiment/tables/sentiment_summary_ar_sarcv2.csv (dev and test, mean over seeds; macro F1 and F1-PN
with their std). Mean rows per generator, per classifier (over its generators) and over every cell. One table per training run on generated data: SR02 (SG01), SR04 (SG02), SR05 (SG03), SR06
(SG03-random), SR07 (SG04) and the repair tests SR08-SR13. SR07-SR13 are test-contaminated (D-023).

Output: docs/sentiment/tables/generation_results.md.

Usage:
  python -m src.sentiment.generation_tables
"""
from __future__ import annotations

import csv
import statistics
import sys
from pathlib import Path

SUMMARY = Path("docs/sentiment/tables/sentiment_summary_ar_sarcv2.csv")
OUT = Path("docs/sentiment/tables/generation_results.md")
RUNS = {"SR02": "SG01", "SR04": "SG02", "SR05": "SG03", "SR06": "SG03-random", "SR07": "SG04",
        "SR08": "SG04 without prayer pairs", "SR09": "SG04 Qwen3 without same-word pairs",
        "SR10": "SG04, two-stage training", "SR11": "SG04 without prayer pairs, two-stage training",
        "SR12": "SG04 POS/NEG pairs only, two-stage training",
        "SR13": "SG04 POS/NEG pairs + NEG sides of jab and remark, two-stage training"}
MODELS = {"marbertv2": "MARBERTv2", "marbert": "MARBERT", "arabertv02_twitter": "AraBERTv02-Tw", "camelbert_mix": "CAMeLBERT-mix",
          "camelbert_da": "CAMeLBERT-DA", "arbert": "ARBERT", "arbertv2": "ARBERTv2", "jais2": "Jais-2-8B"}
GENS = {"fanar": "Fanar", "qwen3": "Qwen3", "aya": "Aya", "jais2": "Jais-2"}
HEADER = ["Classifier", "Generator", "Dev macro F1", "Dev F1-PN", "Dev NEG", "Dev NEU", "Dev POS",
          "Test macro F1", "Test F1-PN", "Test NEG", "Test NEU", "Test POS"]


def table(run: str, rows: list[dict]) -> list[str]:
    """Markdown table of one run: classifier x generator rows, then mean rows per generator, per classifier and overall."""
    scores = {}
    for r in rows:
        if r["run"] == run:
            model, gen = r["folder"].split("_", 1)[1].rsplit("_", 1)
            scores[(model, gen, r["split"])] = r
    pairs = sorted({k[:2] for k in scores}, key=lambda k: (list(MODELS).index(k[0]), list(GENS).index(k[1])))
    lines = ["| " + " | ".join(HEADER) + " |", "|" + "---|" * len(HEADER)]
    for model, gen in pairs:
        cells = [MODELS[model], GENS[gen]]
        for split in ("dev", "test"):
            r = scores[(model, gen, split)]
            cells += [f"{float(r[k]):.2f} ± {float(r[f'{k}_std']):.2f}" for k in ("macro_f1", "f1_pn")]
            cells += [f"{float(r[f'f1_{c}']):.2f}" for c in ("NEG", "NEU", "POS")]
        lines.append("| " + " | ".join(cells) + " |")
    def mean_row(first: str, second: str, cells_of: list[tuple[str, str]]) -> str:
        """A bold row with the mean of every score column over the given classifier x generator cells."""
        cells = [f"**{first}**", f"**{second}**"]
        for split in ("dev", "test"):
            for col in ("macro_f1", "f1_pn", "f1_NEG", "f1_NEU", "f1_POS"):
                cells.append(f"**{statistics.fmean(float(scores[(m, g, split)][col]) for m, g in cells_of):.2f}**")
        return "| " + " | ".join(cells) + " |"

    # Mean over the classifiers of each generator.
    gens = [g for g in GENS if any(p[1] == g for p in pairs)]
    for gen in gens:
        lines.append(mean_row("Mean", GENS[gen], [p for p in pairs if p[1] == gen]))
    # With several generators: mean over the generators of each classifier, then over every cell.
    if len(gens) > 1:
        for model in dict.fromkeys(m for m, _ in pairs):
            lines.append(mean_row(MODELS[model], "Mean", [p for p in pairs if p[0] == model]))
        lines.append(mean_row("Mean", "All", pairs))
    return lines


def main() -> None:
    """Write one table per run."""
    sys.stdout.reconfigure(encoding="utf-8")
    with open(SUMMARY, encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r["eval_corpus"] == r["train_corpus"]]
    md = ["# Results per generation: all classifiers and classes", "",
          "Generated by `python -m src.sentiment.generation_tables` from `sentiment_summary_ar_sarcv2.csv`. Do not edit by hand. "
          "F1 per class, macro F1 and F1-PN (mean F1 of POS and NEG, the official ArSarcasm-v2 metric), mean over seeds. SR07–SR13 are test-contaminated (D-023): their test columns are "
          "leakage analysis.", ""]
    for run, name in RUNS.items():
        md += [f"## {run} (S1 train + {name})", ""] + table(run, rows) + [""]
    OUT.write_text("\n".join(md), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    sys.exit(main())
