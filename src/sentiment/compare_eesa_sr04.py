"""EESA comparison of SR04-EESA (SG02-EESA, targeted few-shot) with its control and baselines (D-034, D-035).

Reads docs/sentiment/tables/sentiment_summary_EESA.csv (from src.sentiment.summarize_runs) and prints the tables;
no files are written (Ammar, 2026-11-10: no new md files without asking). All runs choose the epoch by training loss (D-035):
SR03-EESA real only and SR03-EESA + SG01-EESA (zero-shot; registry run SR03-EESA, D-035), SR04-random-EESA (+ SG02-random-EESA,
few-shot random examples), SR04-EESA (+ SG02-EESA, few-shot error-type examples, dev-contaminated).

Main metric: micro F1 = accuracy (D-033); macro F1 and per-class F1 also shown. Per run and generator: the
mean over the 7 BERTs (each BERT = mean of its 3 seeds). Paired tests: per BERT x generator, the seed-mean
of condition A minus condition B; wins / losses and a two-sided sign test (ties dropped).
BERTs only for now (LLM classifiers are still training).

Usage:
  python -m src.sentiment.compare_eesa_sr04
"""
from __future__ import annotations

import csv
import math
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "docs/sentiment/tables/sentiment_summary_EESA.csv"
BERTS = ["marbertv2", "marbert", "arabertv02_twitter", "arbert", "arbertv2", "camelbert_mix", "camelbert_da"]
GENS = ["qwen3", "aya", "fanar"]
# "SR03-EESA:real" / "SR03-EESA:sg01" = the real-only and the + SG01 members of registry run SR03-EESA.
RUNS = [("SR03-EESA:real", "Real only"), ("SR03-EESA:sg01", "+ SG01-EESA (zero-shot)"),
        ("SR04-random-EESA", "+ SG02-random-EESA (few-shot, random examples)"),
        ("SR04-EESA", "+ SG02-EESA (few-shot, error types; dev-contaminated)")]
METRICS = ["micro_f1", "macro_f1", "f1_NEG", "f1_NEU", "f1_POS"]
PAIRS = [("SR04-EESA", "SR04-random-EESA", "Targeted vs random examples"),
         ("SR04-random-EESA", "SR03-EESA:sg01", "Few-shot vs zero-shot"),
         ("SR04-EESA", "SR03-EESA:real", "Targeted vs real only"),
         ("SR04-random-EESA", "SR03-EESA:real", "Random few-shot vs real only"),
         ("SR03-EESA:sg01", "SR03-EESA:real", "Zero-shot vs real only")]


def sign_test(wins: int, losses: int) -> float:
    """Two-sided exact sign test p-value (ties dropped)."""
    n = wins + losses
    if n == 0:
        return 1.0
    k = min(wins, losses)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    rows = [r for r in csv.DictReader(open(TABLE, encoding="utf-8"))
            if r["train_corpus"] == "EESA" and r["eval_corpus"] == "EESA"]
    # score[(run, bert, gen or "", split)] = {metric: value}
    score = {}
    for r in rows:
        run = r["run"] if r["run"] != "SR03-EESA" else ("SR03-EESA:sg01" if r["generator"] else "SR03-EESA:real")
        if run in dict(RUNS) and r["classifier"] in BERTS:
            score[(run, r["classifier"], r["generator"] or "", r["split"])] = {m: float(r[m]) for m in METRICS}

    def cell(run: str, b: str, g: str, split: str) -> dict | None:
        """Scores of one BERT; real-only runs have no generator, so they match every generator."""
        return score.get((run, b, "" if run == "SR03-EESA:real" else g, split))

    # 1. Means over the BERTs per run x generator (real only: one row).
    table, md = [], ["# EESA: SR04-EESA vs control and baselines (BERTs)", "",
                     "Generated by `python -m src.sentiment.compare_eesa_sr04` from `sentiment_summary_EESA.csv`. "
                     "Do not edit by hand. Epoch by training loss for every run (D-035). Micro F1 = accuracy (D-033), "
                     "the main EESA metric. Mean over the 7 BERTs (3 seeds each). SR04-EESA dev scores are "
                     "dev-contaminated (D-034); test is the fair comparison.", "",
                     "| Run | Training data | Generator | Dev micro F1 | Test micro F1 | Δ test vs real only | Test macro F1 | Test F1 NEG / NEU / POS |",
                     "|---|---|---|---|---|---|---|---|"]
    base = statistics.fmean(cell("SR03-EESA:real", b, "", "test")["micro_f1"] for b in BERTS)
    for run, desc in RUNS:
        for g in ([""] if run == "SR03-EESA:real" else GENS):
            cells = {s: [cell(run, b, g, s) for b in BERTS] for s in ("dev", "test")}
            if any(c is None for c in cells["dev"] + cells["test"]):
                continue
            mean = {s: {m: statistics.fmean(c[m] for c in cells[s]) for m in METRICS} for s in cells}
            table.append({"run": run, "generator": g, **{f"{s}_{m}": round(mean[s][m], 2) for s in mean for m in METRICS}})
            d = mean["test"]["micro_f1"] - base
            md.append(f"| {run} | {desc} | {g or '–'} | {mean['dev']['micro_f1']:.2f} | {mean['test']['micro_f1']:.2f} | "
                      f"{'–' if run == 'SR03-EESA:real' else f'{d:+.2f}'} | {mean['test']['macro_f1']:.2f} | "
                      f"{mean['test']['f1_NEG']:.1f} / {mean['test']['f1_NEU']:.1f} / {mean['test']['f1_POS']:.1f} |")

    # 2. Paired comparisons on test micro F1: 21 BERT x generator pairs.
    md += ["", "## Paired comparisons (test micro F1, 21 BERT × generator pairs)", "",
           "| Comparison | Mean Δ | Wins / losses / ties | Sign test p |", "|---|---|---|---|"]
    for a, b_run, name in PAIRS:
        diffs = [cell(a, b, g, "test")["micro_f1"] - cell(b_run, b, g, "test")["micro_f1"]
                 for b in BERTS for g in GENS if cell(a, b, g, "test") and cell(b_run, b, g, "test")]
        w, l = sum(x > 0 for x in diffs), sum(x < 0 for x in diffs)
        md.append(f"| {name} ({a} − {b_run}) | {statistics.fmean(diffs):+.2f} | {w} / {l} / {len(diffs) - w - l} | "
                  f"{sign_test(w, l):.3f} |")
        table.append({"run": f"{a} - {b_run}", "generator": "pairs", "test_accuracy_mean_delta": round(statistics.fmean(diffs), 3),
                      "wins": w, "losses": l, "p_sign": round(sign_test(w, l), 4)})

    print("\n".join(md))


if __name__ == "__main__":
    main()
