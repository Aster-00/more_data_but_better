"""Layer candidates for SV01 vectors, and their agreement with the SV02 directions (CPU step).

Reads `text_vectors.pt` of `extract.py` (every `text_vector_layer_step`-th layer, S1 train only) and
keeps the non-sarcastic tweets, the groups the pos / neg / neu vectors are built from. In k-fold
cross-validation inside S1 train, per-dialect class vectors from the train folds are scored on the
held-out fold: DiffMean probe macro F1 and Cohen's d per class. Dev and test are never read.

If SV02 vectors of the same generator exist, the cosine of each SV01 class vector with its SV02
counterpart is reported per layer: does the generator's NEG in its own text match NEG in real tweets?
SV02 is only compared here; it is test-contaminated (D-023) and builds nothing.

Outputs in report_dir: metrics.json, report.md, layers.png.

Usage:
  python -m src.sentiment.steering.analyze_real --config configs/sentiment/steering/sv01_fanar.json
  python -m src.sentiment.steering.analyze_real --config configs/sentiment/steering/sv01_fanar.json --limit 48
"""
from __future__ import annotations

import argparse
import json
import random
import sys
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch
from sklearn.metrics import f1_score

from src.data.build_dataset import git_commit
from src.sentiment.steering.analyze_generated import CLASSES, cohens_d, ovr_vector, unit


def cross_validate(X: torch.Tensor, y: np.ndarray, dia: np.ndarray, varieties: list[str], min_n: int,
                   folds: int, seed: int) -> dict:
    """Held-out DiffMean probe F1 and Cohen's d per stored layer, [folds, layers] each."""
    order = list(range(len(y)))
    random.Random(seed).shuffle(order)
    fold = np.empty(len(y), dtype=int)
    fold[order] = np.arange(len(y)) % folds
    n_layers = X.shape[1]
    out = {"f1": np.zeros((folds, n_layers)), "d": {c: np.zeros((folds, n_layers)) for c in CLASSES}}
    for f in range(folds):
        tr, te = np.where(fold != f)[0], np.where(fold == f)[0]
        vecs = {}
        for c in CLASSES:
            v = ovr_vector(X, y, dia, tr, c, varieties, min_n, "per_dialect")
            # Tiny mode can leave a variety too small; fall back to the pooled difference.
            vecs[c] = unit(v if v is not None else ovr_vector(X, y, dia, tr, c, varieties, 1, "pooled"))
        mu = X[tr].mean(0)
        proj = {c: ((X[te] - mu) * vecs[c]).sum(-1).numpy() for c in CLASSES}
        scores = np.stack([proj[c] for c in CLASSES], -1)
        for layer in range(n_layers):
            pred = np.array(CLASSES)[scores[:, layer].argmax(-1)]
            out["f1"][f, layer] = f1_score(y[te], pred, average="macro", labels=list(CLASSES))
            for c in CLASSES:
                out["d"][c][f, layer] = cohens_d(proj[c][y[te] == c, layer], proj[c][y[te] != c, layer])
    return out


def write_report(rep: Path, m: dict) -> None:
    """Markdown summary of metrics.json (generated, never hand-edited)."""
    L = [f"# {m['run_name']}: layer candidates from real S1 train", "",
         "Generated by `src.sentiment.steering.analyze_real`; do not edit. Held-out folds of S1 train, "
         "non-sarcastic tweets. These scores show that classes separate, not that steering works.", "",
         f"- Tweets: {m['n_texts']} ({', '.join(f'{c} {n}' for c, n in m['class_counts'].items())})",
         f"- Best layers by DiffMean F1: {', '.join(str(x) for x in m['top_layers'])}", "",
         "![layers](layers.png)", "",
         "| Layer | DiffMean F1 | d pos | d neg | d neu | Token norm | cos neg | cos neu | cos pos |",
         "|---|---|---|---|---|---|---|---|---|"]
    cos = m.get("cos_with_sv02") or {}
    for i, l in enumerate(m["layers"]):
        c = [f"{cos[k][i]:.2f}" if k in cos else "–" for k in ("neg", "neu", "pos")]
        L.append(f"| {l} | {m['f1_mean'][i]:.3f} ± {m['f1_sd'][i]:.3f} | {m['d']['POS'][i]:.2f} | {m['d']['NEG'][i]:.2f} | "
                 f"{m['d']['NEU'][i]:.2f} | {m['token_norm'][i]:.1f} | {c[0]} | {c[1]} | {c[2]} |")
    L += ["", "cos = cosine of the SV01 class vector with its SV02 counterpart (same generator).", ""]
    with open(rep / "report.md", "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))


def main() -> None:
    """CLI entry point."""
    sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--config", type=Path, required=True)
    p.add_argument("--limit", type=int, default=None, help="analyse the tiny-mode extraction (_limitN)")
    p.add_argument("--folds", type=int, default=5)
    p.add_argument("--compare", type=Path, default=Path("data/steering/sv02_sg04_fanar/vectors.pt"))
    args = p.parse_args()
    with open(args.config, encoding="utf-8") as f:
        cfg = json.load(f)
    data_dir = Path(cfg["output_dir"])
    rep = Path("results/sentiment/steering") / data_dir.name
    min_n = cfg["min_group_size"]
    if args.limit is not None:
        data_dir = data_dir.with_name(data_dir.name + f"_limit{args.limit}")
        rep = rep.with_name(rep.name + f"_limit{args.limit}")
        args.folds, min_n = 2, 1
    rep.mkdir(parents=True, exist_ok=True)
    t0 = time.time()

    tv = torch.load(data_dir / "text_vectors.pt", weights_only=False)
    vec = torch.load(data_dir / "vectors.pt", weights_only=False)
    keep = np.where(~np.array(tv["sarcasm"]))[0]
    X = tv["vectors"][keep].float()                                    # [N, stored layers, H]
    y, dia = np.array(tv["sentiment"])[keep], np.array(tv["dialect"])[keep]
    layers = list(tv["layers"])
    print(f"{len(y)} non-sarcastic tweets, stored layers {layers}", flush=True)

    cv = cross_validate(X, y, dia, cfg["varieties"], min_n, args.folds, cfg["seed"])
    f1 = cv["f1"].mean(0)
    # Candidates: embeddings and the final (normed) layer left out, as in SV02.
    inner = [i for i, l in enumerate(layers) if 0 < l < len(vec["token_norm_mean"]) - 1]
    top = sorted(inner, key=lambda i: -f1[i])[:3]

    # Agreement with the SV02 directions on the stored layers.
    cos = None
    if args.compare.exists():
        other = torch.load(args.compare, weights_only=False)["vectors"]
        cos = {n: [round(float(vec["vectors"][n]["per_dialect"][l] @ other[n]["per_dialect"][l]), 3) for l in layers]
               for n in ("neg", "neu", "pos") if "per_dialect" in vec["vectors"].get(n, {}) and n in other}

    metrics = {"run_name": cfg["run_name"], "generator": cfg["generator"], "n_texts": int(len(y)),
               "class_counts": {c: int((y == c).sum()) for c in CLASSES}, "layers": layers,
               "top_layers": [layers[i] for i in top], "f1_mean": cv["f1"].mean(0).round(4).tolist(),
               "f1_sd": cv["f1"].std(0).round(4).tolist(),
               "d": {c: np.nanmean(v, 0).round(3).tolist() for c, v in cv["d"].items()},
               "token_norm": [round(float(vec["token_norm_mean"][l]), 2) for l in layers],
               "cos_with_sv02": cos, "compared_with": str(args.compare) if cos else None, "folds": args.folds,
               "git_commit": git_commit(), "seconds": round(time.time() - t0),
               "finished": time.strftime("%Y-%m-%d %H:%M")}
    with open(rep / "metrics.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump(metrics, f, ensure_ascii=False, indent=1)

    # One figure: separation by layer, and agreement with SV02 if available.
    fig, axs = plt.subplots(1, 2, figsize=(12, 4))
    axs[0].plot(layers, f1, label="DiffMean probe macro F1")
    axs[0].fill_between(layers, f1 - cv["f1"].std(0), f1 + cv["f1"].std(0), alpha=0.2)
    axs[0].set(xlabel="layer (0 = embeddings)", ylabel="held-out macro F1", title=f"{cfg['run_name']}: S1 train folds")
    axs[0].legend()
    for n, v in (cos or {}).items():
        axs[1].plot(layers, v, label=f"v_{n}")
    axs[1].axhline(0, c="grey", lw=1)
    axs[1].set(xlabel="layer", ylabel="cosine", title="SV01 (real) against SV02 (own SG04 text)")
    axs[1].legend()
    fig.tight_layout(); fig.savefig(rep / "layers.png", dpi=130); plt.close(fig)
    write_report(rep, metrics)
    print(f"saved {rep} ({metrics['seconds']}s); best layers {metrics['top_layers']}", flush=True)


if __name__ == "__main__":
    sys.exit(main())
