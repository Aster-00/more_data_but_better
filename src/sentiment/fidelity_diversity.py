"""Fidelity against diversity for every sentiment set (real S1, SG01, SG02): the table.

Reads only logged quality results, nothing is recomputed:
  results/quality/sentiment/sg01_quality.json, sg02_quality.json   SQ01 / SQ02 (fidelity, MTLD, Vendi,
                                                                    topic spread of 30 ArSarcasm-v2 topics)
  results/quality/sentiment/universal_topics.json                   SQ03 (universal topic list)
Fidelity = share of texts whose requested sentiment the SR01 MARBERT ensemble predicts. For the real
row it is that ensemble's accuracy on S1 dev (a different quantity: on real train it would be
in-sample), so the real point is a reference, not a like-for-like fidelity.
Distance to real = Jensen-Shannon divergence (base 2) between a set's universal topic shares
(18 named topics + unnamed) and those of S1 train; lower = closer topic mix.

Outputs: docs/sentiment/tables/fidelity_diversity.{csv,md}. The figure is drawn in notebooks/fidelity_diversity.ipynb.

Usage:
  python -m src.sentiment.fidelity_diversity
"""
from __future__ import annotations

import csv
import json
import math
import sys
from pathlib import Path

QUALITY = Path("results/quality/sentiment")
TABLES = Path("docs/sentiment/tables")
GENERATORS = {"jais2": "Jais-2", "fanar": "Fanar", "qwen3": "Qwen3", "aya": "Aya"}


def js_divergence(p: dict, q: dict) -> float:
    """Jensen-Shannon divergence (base 2) of two share dictionaries."""
    keys = set(p) | set(q)
    m = {k: (p.get(k, 0) + q.get(k, 0)) / 2 for k in keys}
    kl = lambda a: sum(a[k] * math.log2(a[k] / m[k]) for k in keys if a.get(k, 0) > 0)
    return (kl(p) + kl(q)) / 2


def collect() -> list[dict]:
    """One row per set: name, run, generator, fidelity and every diversity measure."""
    uni = json.loads((QUALITY / "universal_topics.json").read_text(encoding="utf-8"))["sets"]
    ref = uni["S1 real train"]["topic_shares"]
    rows = []
    for run in ("sg01", "sg02"):
        sq = json.loads((QUALITY / f"{run}_quality.json").read_text(encoding="utf-8"))["sets"]
        for g, s in sq.items():
            # The real reference row is the same in both files; keep it once.
            if g == "real" and run == "sg02":
                continue
            u = uni["S1 real train"] if g == "real" else uni[f"{run.upper()} {GENERATORS[g]}"]
            rows.append({"set": "S1 real (reference)" if g == "real" else f"{run.upper()} {GENERATORS[g]}",
                         "run": "real" if g == "real" else run, "generator": g,
                         "fidelity": s["fidelity"], "fidelity_NEU": s["fidelity_per_class"]["NEU"],
                         "mtld": s["mtld"], "vendi": s["vendi"], "topic_spread": s["topic_spread"],
                         "effective_named": u["effective_named"],
                         "distance_to_real": js_divergence(u["topic_shares"], ref)})
    return rows


def write_tables(rows: list[dict]) -> None:
    """CSV with full precision and a Markdown table."""
    TABLES.mkdir(parents=True, exist_ok=True)
    cols = ["set", "fidelity", "fidelity_NEU", "mtld", "vendi", "topic_spread", "effective_named", "distance_to_real"]
    with open(TABLES / "fidelity_diversity.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for r in rows:
            w.writerow([r[c] for c in cols])
    md = ["# Fidelity against diversity", "",
          "Generated by `python -m src.sentiment.fidelity_diversity` from SQ01, SQ02 and SQ03. Do not edit by hand. "
          "Real fidelity = accuracy of the same classifiers on S1 dev (reference only).", "",
          "| Set | Fidelity | Fidelity NEU | MTLD | Vendi | Topic spread (of 30) | Effective universal topics (of 18) | Distance to real |",
          "|---|---|---|---|---|---|---|---|"]
    md += [f"| {r['set']} | {r['fidelity']:.1%} | {r['fidelity_NEU']:.1%} | {r['mtld']:.0f} | {r['vendi']:.2f} | {r['topic_spread']} | "
           f"{r['effective_named']:.1f} | {r['distance_to_real']:.3f} |" for r in rows]
    (TABLES / "fidelity_diversity.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(md[4:]))


def main() -> None:
    """Collect and write the tables."""
    sys.stdout.reconfigure(encoding="utf-8")
    write_tables(collect())


if __name__ == "__main__":
    sys.exit(main())
